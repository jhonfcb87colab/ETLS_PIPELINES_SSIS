INSERT INTO TMP_BORRAR_LOCAL.DBO.INFO_MANIFIESTOS_VOLUMEN_PIEZAS
SELECT TDOC.ID_PROCESO, TDOC.NUMERO_MOVIMI,TDOC.CONSECUT_MOVIMI, 
SUM(GMVP.PESO_VOLU) AS PESO_VOLU_TOTAL,
SUM(GMVP.PESO_FISICO) AS PESO_FISICO_TOTAL,SUM(GMVP.NUMERO_PIEZAS) AS NUMERO_PIEZAS_TOTAL 
FROM TMP_BORRAR_LOCAL.DBO.DOCUMENTOS_MECE_LOGISTICO_RED_OPERATIVA TDOC (NOLOCK)
INNER JOIN Mece_Logistico.DBO.SEGUIMIENTO_ENVIO SE (NOLOCK) ON SE.ID_PROCESO=TDOC.ID_PROCESO
	AND SE.NUMERO_MOVIMI=TDOC.NUMERO_MOVIMI AND SE.CONSECUT_MOVIMI=TDOC.CONSECUT_MOVIMI
INNER JOIN TMP_BORRAR_LOCAL.DBO.INFO_GUIAS_MANIFIESTOS_VOLUMEN_PIEZAS GMVP (NOLOCK) ON GMVP.NUMERO_GUIA=SE.NUMERO_GUIA
LEFT JOIN TMP_BORRAR_LOCAL.DBO.INFO_MANIFIESTOS_VOLUMEN_PIEZAS MVP (NOLOCK) ON MVP.ID_PROCESO=TDOC.ID_PROCESO 
	AND MVP.NUMERO_MOVIMI=TDOC.NUMERO_MOVIMI AND MVP.CONSECUT_MOVIMI=TDOC.CONSECUT_MOVIMI
WHERE MVP.ID_PROCESO IS NULL AND MVP.NUMERO_MOVIMI IS NULL AND MVP.CONSECUT_MOVIMI IS NULL
--TDOC.ID_PROCESO=9 AND TDOC.NUMERO_MOVIMI='001002001931008032025' AND TDOC.CONSECUT_MOVIMI=2
GROUP BY   TDOC.ID_PROCESO, TDOC.NUMERO_MOVIMI,TDOC.CONSECUT_MOVIMI



